/**
 * The rulebook (ADR 0016 §9): Markdown generated from a domain's docs — an index, a page per
 * topic, the glossary and the questions — and the schemas merged with its profile, for the
 * editor. Committed beside the sources; the model check fails when it is stale.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { MachineDef, Model, StateDef } from "@statestorm/kernel";
import type { Docs, Rule, Topic, Trace } from "./docs.ts";
import { SCHEMA_NAMES } from "./docs.ts";
import { REFERENCE } from "../groups.ts";
import { packageTypes } from "../boundaries.ts";

const BANNER = (from: string) => `<!-- Generated by \`statestorm docs\` from ${from} — edit that, not this. -->\n`;
const cell = (s: unknown) => String(s ?? "").replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|");
const PAST = { refines: "refined", revises: "revised", supersedes: "superseded" } as const;
const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;

/**
 * What a topic's types do, from the model: the commands they take, the events they raise, the
 * policies that react. A package's types are those it lists and its aggregates' entities (ADR 0013).
 */
export function derived(model: Model, packaged: Map<string, string[]>, topic: Topic) {
  const names = new Set([...(topic.canvas?.packages ?? []).flatMap((p) => packaged.get(p) ?? []), ...(topic.canvas?.types ?? [])]);
  const commands = new Set<string>();
  const events = new Set<string>();
  const walk = (states: Record<string, StateDef>) => {
    for (const s of Object.values(states)) {
      for (const [name, list] of Object.entries(s.on)) { commands.add(name); for (const t of list) t.emit.forEach((e) => events.add(e.event)); }
      for (const t of [...s.onChildren.map((c) => c.transition), ...s.after.map((a) => a.transition), ...(s.onDone ? [s.onDone] : [])]) t.emit.forEach((e) => events.add(e.event));
      [...s.emitOnEntry, ...s.emitOnExit].forEach((e) => events.add(e.event));
      walk(s.states);
    }
  };
  for (const n of names) { const m = model.aggregates[n]; if (m) walk(m.states); }
  const reacts = (p: MachineDef) => {
    const on = new Set<string>();
    const all = (states: Record<string, StateDef>) => { for (const s of Object.values(states)) { Object.keys(s.on).forEach((e) => on.add(e)); all(s.states); } };
    all(p.states);
    return [...on].filter((e) => events.has(e));
  };
  const policies = Object.values(model.policies).map((p) => ({ name: p.name, on: reacts(p) })).filter((p) => p.on.length);
  return { types: [...names], commands: [...commands].sort(), events: [...events].sort(), policies };
}

export function rulebook(docs: Docs, model: Model, t: Trace): Map<string, string> {
  const files = new Map<string, string>();
  const packaged = packageTypes(model);
  const topicOf = new Map(docs.topics.flatMap((tp) => tp.rules.map((r) => [r.id, tp.file] as const)));
  const link = (id: string) => {
    const kind = t.ids.get(id)?.kind;
    if (kind === "rule") return `[${id}](${topicOf.get(id)}.md#${id})`;
    if (kind === "question") return `[${id}](questions.md#${id})`;
    const m = REFERENCE.exec(id);
    const url = m ? docs.profile.external?.[m[1]!]?.url : undefined;
    return url ? `[${id}](${url.replace("{id}", id)})` : id;
  };
  const links = (ids: string[] | undefined) => (ids ?? []).map(link).join(", ");
  const extras = (o: Record<string, unknown>, fields: Record<string, { description: string }> | undefined) =>
    Object.keys(fields ?? {}).filter((k) => o[k] !== undefined).map((k) => `**${k}:** ${Array.isArray(o[k]) ? (o[k] as unknown[]).join(", ") : String(o[k])}`);
  const openQuestions = (id: string) => docs.questions.filter((q) => q.status === "open" && q.about?.includes(id)).map((q) => q.id);

  const ruleMd = (r: Rule) => {
    const c = t.cited.get(r.id);
    const decided = r.decided
      ? `decided ${r.decided.session !== undefined ? `in session ${r.decided.session}, ` : ""}${r.decided.date}${r.decided.questions?.length ? `, answering ${links(r.decided.questions)}` : ""}`
      : "";
    const changed = ["refines", "revises", "supersedes"].flatMap((how) => ((r as Record<string, unknown>)[how] as string[] | undefined)?.length ? [`${how} ${links((r as Record<string, unknown>)[how] as string[])}`] : []);
    const by = t.changedBy.get(r.id) ?? [];
    const lines = [
      `<a id="${r.id}"></a>`,
      `### ${r.id} — ${r.status === "superseded" ? `~~${r.title}~~` : r.title}`,
      "",
      [`\`${r.status}\``, r.kind, decided, ...changed].filter(Boolean).join(" · "),
      ...(extras(r, docs.profile.fields?.rule).length ? ["", extras(r, docs.profile.fields?.rule).join(" · ")] : []),
      "",
      r.text.trim(),
    ];
    if (r.table) {
      lines.push("", `| ${r.table.columns.map(cell).join(" | ")} |`, `|${r.table.columns.map(() => "---").join("|")}|`);
      for (const row of r.table.rows) lines.push(`| ${row.map(cell).join(" | ")} |`);
    }
    const facts = [
      by.length && `**Since:** ${by.map((b) => `${PAST[b.how]} by ${link(b.by)}`).join(", ")}`,
      c?.model.length && `**Model:** ${c.model.map((w) => `\`${w}\``).join(", ")}`,
      c?.scenarios.length && `**Shown by:** ${c.scenarios.join(", ")}`,
      c?.issues.length && `**Drawing issues:** ${c.issues.join(", ")}`,
      openQuestions(r.id).length && `**Open questions:** ${links(openQuestions(r.id))}`,
      r.untraced && `**Untraced:** ${r.untraced}`,
    ].filter(Boolean);
    if (facts.length) lines.push("", ...facts.map((f) => `- ${f}`));
    return lines.join("\n");
  };

  // ---- a page per topic
  for (const tp of docs.topics) {
    const d = derived(model, packaged, tp);
    const head = [
      BANNER(`docs/rules/${tp.file}.yaml`),
      `# ${tp.title}`,
      "",
      ...(tp.canvas?.purpose ? [`> ${tp.canvas.purpose.trim().replace(/\n/g, "\n> ")}`, ""] : []),
      ...(d.types.length ? [
        `**Types:** ${d.types.map((x) => `\`${x}\``).join(", ")}${tp.canvas?.packages?.length ? ` (package${tp.canvas.packages.length === 1 ? "" : "s"} ${tp.canvas.packages.join(", ")})` : ""}`,
        "",
        `**Commands in:** ${d.commands.join(", ") || "—"}`,
        "",
        `**Events out:** ${d.events.join(", ") || "—"}`,
        "",
        `**Policies reacting:** ${d.policies.map((p) => `${p.name} (on ${p.on.join(", ")})`).join("; ") || "—"}`,
        "",
      ] : []),
      `[All topics](index.md)`,
      "",
      "## Rules",
      "",
      "",
    ];
    files.set(`rulebook/${tp.file}.md`, `${head.join("\n")}${tp.rules.map(ruleMd).join("\n\n")}\n`);
  }

  // ---- the index: one line per rule
  const rules = docs.topics.flatMap((tp) => tp.rules);
  const count = (s: string) => rules.filter((r) => r.status === s).length;
  const open = docs.questions.filter((q) => q.status === "open");
  const index = [
    BANNER("docs/"),
    "# Rulebook",
    "",
    `${plural(rules.length, "rule")} in ${plural(docs.topics.length, "topic")}: ${count("agreed")} agreed, ${count("to-confirm")} to confirm, ${count("deferred")} deferred, ${count("superseded")} superseded.`
      + ` ${open.length ? `[${plural(open.length, "open question")}](questions.md).` : "No open questions."}${docs.glossary ? " The terms are in the [glossary](glossary.md)." : ""}`,
    "",
  ];
  for (const tp of docs.topics) {
    index.push(`## [${tp.title}](${tp.file}.md)`, "", "| id | status | rule |", "|---|---|---|");
    for (const r of tp.rules) index.push(`| [${r.id}](${tp.file}.md#${r.id}) | ${r.status} | ${cell(r.title)} |`);
    index.push("");
  }
  files.set("rulebook/index.md", index.join("\n"));

  // ---- the glossary
  if (docs.glossary) {
    const g = [BANNER("docs/glossary.yaml"), "# Glossary", "", "[All topics](index.md)", ""];
    for (const term of [...docs.glossary].sort((a, b) => a.term.localeCompare(b.term))) {
      g.push(`### ${term.term}${term.aka?.length ? ` (${term.aka.join(", ")})` : ""}`, "", term.definition.trim());
      const facts = [
        term.model?.length && `**In the model:** ${term.model.map((m) => `\`${m}\``).join(", ")}`,
        ...extras(term, docs.profile.fields?.term),
        ...(term.avoid ?? []).map((a) => `**Not:** *${a.word}* — ${a.why}`),
      ].filter(Boolean);
      if (facts.length) g.push("", ...facts.map((f) => `- ${f}`));
      g.push("");
    }
    files.set("rulebook/glossary.md", g.join("\n"));
  }

  // ---- the questions: open first
  if (docs.questions.length) {
    const q = [BANNER("docs/questions.yaml"), "# Questions", "", "[All topics](index.md)", ""];
    for (const [title, status] of [["Open", "open"], ["Answered", "answered"], ["Withdrawn", "withdrawn"]] as const) {
      const list = docs.questions.filter((x) => x.status === status);
      if (!list.length) continue;
      q.push(`## ${title}`, "");
      for (const x of list) {
        q.push(`<a id="${x.id}"></a>`, `### ${x.id} — ${x.question.trim()}`, "");
        const facts = [
          `**Leaning:** ${x.leaning}`,
          ...(x.options ?? []).map((o) => `**Option:** ${o.option} — ${o.consequence}`),
          x.about?.length && `**About:** ${links(x.about)}`,
          `**Asked:** ${x.asked.session !== undefined ? `session ${x.asked.session}, ` : ""}${x.asked.date}`,
          x.answer && `**${status === "withdrawn" ? "Withdrawn" : "Answer"}:** ${x.answer.trim()}`,
          x.answeredBy?.length && `**Recorded in:** ${links(x.answeredBy)}`,
          ...extras(x, docs.profile.fields?.question),
        ].filter(Boolean);
        q.push(...facts.map((f) => `- ${f}`), "");
      }
    }
    files.set("rulebook/questions.md", q.join("\n"));
  }

  // ---- the schemas the domain's files are written against
  for (const n of SCHEMA_NAMES) files.set(`.schemas/${n}.schema.json`, `${JSON.stringify(docs.schemas[n], null, 2)}\n`);
  return files;
}

/** The generated files that differ from what is on disk — missing, changed, or no longer generated. */
export function staleFiles(dir: string, files: Map<string, string>): string[] {
  const out: string[] = [];
  for (const [f, text] of files) if (!existsSync(join(dir, f)) || readFileSync(join(dir, f), "utf8") !== text) out.push(f);
  for (const sub of ["rulebook", ".schemas"]) {
    if (!existsSync(join(dir, sub))) continue;
    for (const f of readdirSync(join(dir, sub))) if (!files.has(`${sub}/${f}`)) out.push(`${sub}/${f}`);
  }
  return out;
}
